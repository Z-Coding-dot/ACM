import React from 'react';
import ReactDOM from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { LazyMotion, MotionConfig } from 'framer-motion';
import { PwaProvider } from './app/pwa';
import { AuthProvider } from './app/workspace';
import { AppRouter } from './app/router';
import { ErrorBoundary } from './app/error-boundary';
import './i18n';
import '@fontsource/inter/latin-400.css';
import '@fontsource/inter/latin-500.css';
import '@fontsource/inter/latin-600.css';
import '@fontsource/vazirmatn/arabic-400.css';
import '@fontsource/vazirmatn/arabic-500.css';
import '@fontsource/vazirmatn/arabic-600.css';
import './styles.css';
const queryClient = new QueryClient({ defaultOptions: { queries: { retry: false, staleTime: 20000, refetchOnWindowFocus: false }, mutations: { retry: false, networkMode: 'always' } } });
const loadMotion = () => import('./lib/motion-features').then(module => module.default);
ReactDOM.createRoot(document.getElementById('root')!).render(<React.StrictMode><ErrorBoundary><LazyMotion features={loadMotion} strict><MotionConfig reducedMotion="user"><QueryClientProvider client={queryClient}><BrowserRouter><PwaProvider><AuthProvider><AppRouter /></AuthProvider></PwaProvider></BrowserRouter></QueryClientProvider></MotionConfig></LazyMotion></ErrorBoundary></React.StrictMode>);
